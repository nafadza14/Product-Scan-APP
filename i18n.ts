export const conditionKey = (c: HealthCondition): TranslationKey => ({
  [HealthCondition.PREGNANCY]: 'condPregnancy',
  [HealthCondition.CANCER_CARE]: 'condCancer',
  [HealthCondition.AUTOIMMUNE]: 'condAutoimmune',
  [HealthCondition.ALLERGIES]: 'condAllergies',
  [HealthCondition.GENERAL_HEALTH]: 'condGeneral',
  [HealthCondition.MORE_DISEASES]: 'condOther',
  [HealthCondition.NONE]: 'condGeneral'
}[c] as TranslationKey);

export const conditionLabel = (
  t: Translator,
  profile: { condition: HealthCondition; customConditionName?: string } | null
): string => {
  if (!profile) return t('condGeneral');
  if (profile.condition === HealthCondition.MORE_DISEASES && profile.customConditionName) return profile.customConditionName;
  return t(conditionKey(profile.condition));
};

export const timeAgo = (t: Translator, ts: number): string => {
  const s = Math.floor((Date.now() - ts) / 1000);
  if (s < 60) return t('justNow');
  const m = Math.floor(s / 60);
  if (m < 60) return t('minutesAgo', { n: m });
  const h = Math.floor(m / 60);
  if (h < 24) return t('hoursAgo', { n: h });
  return t('daysAgo', { n: Math.floor(h / 24) });
};
